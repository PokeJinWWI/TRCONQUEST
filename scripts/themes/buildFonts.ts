// Writes src/themes/nervFonts.css from the installed @fontsource packages: only the weights the
// NERV theme uses, woff2 only (every browser the game runs in has it), each CJK font split by
// unicode-range so a page downloads only the slices holding the characters it shows.
// Rerun after upgrading a @fontsource package:  npx tsx scripts/themes/buildFonts.ts
import { readFileSync, writeFileSync } from 'node:fs'

const FACES: [pkg: string, weight: number][] = [
  ['oswald', 500],
  ['oswald', 700],
  ['barlow-condensed', 500],
  ['barlow-condensed', 600],
  ['fira-code', 400],
  ['fira-code', 500],
  ['noto-serif-jp', 900],
  ['noto-serif-tc', 900],
  ['noto-serif-sc', 900],
  ['noto-sans-jp', 900],
  ['noto-sans-tc', 900],
  ['noto-sans-sc', 900],
  // Regular weight: translated description paragraphs (heavy type is for labels only).
  ['noto-sans-jp', 400],
  ['noto-sans-tc', 400],
  ['noto-sans-sc', 400],
]

let out = '/* GENERATED by scripts/themes/buildFonts.ts — do not edit by hand. Fonts of the NERV theme (themes/nerv.css). */\n'
for (const [pkg, weight] of FACES) {
  const css = readFileSync(`node_modules/@fontsource/${pkg}/${weight}.css`, 'utf8')
  for (const block of css.match(/@font-face\s*{[^}]*}/g) ?? []) {
    const woff2 = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)
    if (!woff2) continue
    const src = `src: url(../../node_modules/@fontsource/${pkg}/files/${woff2[1]}) format('woff2');`
    out += block.replace(/src:[^;]*;/, src).replace(/\n\s*/g, ' ') + '\n'
  }
}
writeFileSync('src/themes/nervFonts.css', out)
console.log(`wrote src/themes/nervFonts.css (${out.split('\n').length - 2} faces)`)
