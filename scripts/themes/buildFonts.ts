// Writes src/themes/nervFonts.css, ichorFonts.css and yesteryearFonts.css from the installed @fontsource
// packages: only the weights each theme uses, woff2 only (every browser the game runs in has it).
// NERV's CJK fonts are split by unicode-range so a page downloads only the slices holding the
// characters it shows; Ichor and Yesteryear are English only, so they keep just the Latin slices.
// Rerun after upgrading a @fontsource package:  npx tsx scripts/themes/buildFonts.ts
import { readFileSync, writeFileSync } from 'node:fs'

// [package, css file stem in node_modules/@fontsource/<package>/ (a weight, or 'weight-italic')]
type Face = [pkg: string, stem: string]

const NERV: Face[] = [
  ['oswald', '500'],
  ['oswald', '700'],
  ['barlow-condensed', '500'],
  ['barlow-condensed', '600'],
  ['fira-code', '400'],
  ['fira-code', '500'],
  ['noto-serif-jp', '900'],
  ['noto-serif-tc', '900'],
  ['noto-serif-sc', '900'],
  ['noto-sans-jp', '900'],
  ['noto-sans-tc', '900'],
  ['noto-sans-sc', '900'],
  // Regular weight: translated description paragraphs (heavy type is for labels only).
  ['noto-sans-jp', '400'],
  ['noto-sans-tc', '400'],
  ['noto-sans-sc', '400'],
]

const ICHOR: Face[] = [
  // Headings and window titles: engraved Roman capitals.
  ['cinzel', '500'],
  ['cinzel', '700'],
  // Body and interface text: an elegant old-style serif.
  ['cormorant-garamond', '500'],
  ['cormorant-garamond', '600'],
  ['cormorant-garamond', '700'],
  ['cormorant-garamond', '600-italic'],
  // The title of the game: a modern, angular blackletter (narrow, straight-sided, sharp-cut).
  ['pirata-one', '400'],
]

const YESTERYEAR: Face[] = [
  // Headings, window titles and figures: a high-contrast Didone, the type of 1900s playing cards and bills.
  ['playfair-display', '500'],
  ['playfair-display', '700'],
  ['playfair-display', '500-italic'],
  // Body and interface text: a genuine turn-of-the-century book face.
  ['old-standard-tt', '400'],
  ['old-standard-tt', '700'],
  ['old-standard-tt', '400-italic'],
  // The title of the game: saloon wood type.
  ['rye', '400'],
]

function build(faces: Face[], out: string, header: string, keep: (file: string) => boolean): number {
  let css = header + '\n'
  let n = 0
  for (const [pkg, stem] of faces) {
    const source = readFileSync(`node_modules/@fontsource/${pkg}/${stem}.css`, 'utf8')
    for (const block of source.match(/@font-face\s*{[^}]*}/g) ?? []) {
      const woff2 = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)
      if (!woff2 || !keep(woff2[1])) continue
      const src = `src: url(../../node_modules/@fontsource/${pkg}/files/${woff2[1]}) format('woff2');`
      css += block.replace(/src:[^;]*;/, src).replace(/\n\s*/g, ' ') + '\n'
      n++
    }
  }
  writeFileSync(out, css)
  return n
}

const all = () => true
// '<family>-latin-<weight>-<style>.woff2' and '-latin-ext-'; a file name may also carry other subsets.
const latin = (file: string) => /-latin(-ext)?-\d+-(normal|italic)\.woff2$/.test(file)

const nerv = build(NERV, 'src/themes/nervFonts.css', '/* GENERATED by scripts/themes/buildFonts.ts — do not edit by hand. Fonts of the NERV theme (themes/nerv.css). */', all)
const ichor = build(ICHOR, 'src/themes/ichorFonts.css', '/* GENERATED by scripts/themes/buildFonts.ts — do not edit by hand. Fonts of the Ichor theme (themes/ichor.css). */', latin)
const yesteryear = build(YESTERYEAR, 'src/themes/yesteryearFonts.css', '/* GENERATED by scripts/themes/buildFonts.ts — do not edit by hand. Fonts of the Yesteryear theme (themes/yesteryear.css). */', latin)
console.log(`wrote nervFonts.css (${nerv} faces), ichorFonts.css (${ichor}) and yesteryearFonts.css (${yesteryear}) in src/themes`)
