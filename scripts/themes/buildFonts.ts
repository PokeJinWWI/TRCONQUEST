function build(faces: Face[], out: string, header: string, keep: (file: string) => boolean): number {
  let css = header + '\n'
  let n = 0
  for (const [pkg, stem] of faces) {
    const source = readFileSync(`node_modules/@fontsource/${pkg}/${stem}.css`, 'utf8')
    for (const block of source.match(/@font-face\s*{[^}]*}/g) ?? []) {
      const woff2 = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)
      if (!woff2 || !keep(woff2[1])) continue
      const src = `src: url(../../node_modules/@fontsource/${pkg}/files/${woff2[1]}) format('woff2');`
      css += block.replace(/src:[^;]*;/, src).replace(/\n\s*/g, ' ') + '\n'
      n++
    }
  }
  writeFileSync(out, css)
  return n
}

