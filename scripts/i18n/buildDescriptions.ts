// Builds src/i18n/descriptions.ts from scripts/i18n/desc/*.json (each a list of
// { en, ja, zhHant, zhHans }): the full translations of the game's descriptions, shown under the
// English in the NERV theme. Run after adding or editing a batch:
//   npx tsx scripts/i18n/buildDescriptions.ts
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

interface Entry { en: string; ja: string; zhHant: string; zhHans: string }
const norm = (s: string) => s.replace(/\s+/g, ' ').trim()
const all = new Map<string, Entry>()
for (const f of readdirSync('scripts/i18n/desc').filter((f) => f.endsWith('.json')).sort()) {
  for (const e of JSON.parse(readFileSync(`scripts/i18n/desc/${f}`, 'utf8')) as Entry[]) {
    if (!e.en || !e.ja || !e.zhHant || !e.zhHans) throw new Error(`${f}: an entry is missing a script: ${e.en?.slice(0, 40)}`)
    all.set(norm(e.en), e)
  }
}
const rows = [...all.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([en, e]) => `  ${JSON.stringify(en)}: [${JSON.stringify(e.ja)}, ${JSON.stringify(e.zhHant)}, ${JSON.stringify(e.zhHans)}],`)
writeFileSync('src/i18n/descriptions.ts', `// GENERATED by scripts/i18n/buildDescriptions.ts from scripts/i18n/desc/*.json — edit those, not this file.\n// English description (whitespace-normalized) -> [Japanese, Traditional Chinese, Simplified Chinese].\nexport const DESCRIPTIONS: Record<string, [string, string, string]> = {\n${rows.join('\n')}\n}\n`)
console.log(`${all.size} descriptions`)
