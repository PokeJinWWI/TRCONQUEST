// Builds src/i18n/{ja,zhHant,zhHans}.ts from scripts/i18n/terms.tsv (English, Japanese,
// Traditional Chinese, Simplified Chinese per line). Run after editing the table:
//   npx tsx scripts/i18n/buildDicts.ts
import { readFileSync, writeFileSync } from 'node:fs'

const rows = readFileSync('scripts/i18n/terms.tsv', 'utf8')
  .split('\n')
  .filter((l) => l.trim() && !l.startsWith('#'))
  .map((l) => l.split('\t'))
const bad = rows.filter((r) => r.length !== 4 || r.some((c) => !c.trim()))
if (bad.length) throw new Error(`terms.tsv: ${bad.length} malformed line(s), e.g. ${JSON.stringify(bad[0])}`)
const seen = new Map<string, string[]>()
for (const r of rows) {
  const prev = seen.get(r[0])
  if (prev && prev.join('|') !== r.join('|')) throw new Error(`terms.tsv: "${r[0]}" twice with different translations`)
  seen.set(r[0], r)
}
const entries = [...seen.values()].sort((a, b) => a[0].localeCompare(b[0]))
const out = (name: string, col: number, file: string) =>
  writeFileSync(
    file,
    `// GENERATED by scripts/i18n/buildDicts.ts from scripts/i18n/terms.tsv — edit the table, not this file.\nexport const ${name}: Record<string, string> = {\n${entries.map((r) => `  ${JSON.stringify(r[0])}: ${JSON.stringify(r[col])},`).join('\n')}\n}\n`,
  )
out('JA', 1, 'src/i18n/ja.ts')
out('ZH_HANT', 2, 'src/i18n/zhHant.ts')
out('ZH_HANS', 3, 'src/i18n/zhHans.ts')
console.log(`${entries.length} terms`)
